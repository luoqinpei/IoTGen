'''
This script evaluates PCB layouts generated by the LayoutAgent using different models.
It iterates through the modules in the dataset, checks if they have already been processed, and if not, it creates a LayoutAgent instance for each module and runs the iterative PCB layout process. The scores from each iteration are recorded in a JSONL file for later analysis. The script also handles skipping modules that have already been processed or do not match the expected filename pattern, ensuring that only relevant modules are evaluated.¸
'''

import os, sys, json
from pathlib import Path
import re

project_path = os.environ["PROJECT_PATH"]
sys.path.append(project_path)

from layout_agent import LayoutAgent


OUTPUT_JSONL = os.path.join(project_path, "pcb_layout", "layout_scores_grok.jsonl")
REFERENCE_JSONL = os.path.join(project_path, "pcb_layout", "layout_scores.jsonl")


def record_scores(module_dir: Path, module_name: str, scores: list[float]):
    """
    Save step 0, step 1, and max to JSONL.
    scores is expected to be a list of numeric scores (freerouting).
    """
    if not scores:
        result = {
            "module_dir": str(module_dir.stem),
            "module_dir": str(module_dir),
            "module": module_name,
            "step0": None,
            "step1": None,
            "max_score": None,
        }
    else:
        step0 = scores[0] if len(scores) > 0 else None
        step1 = scores[1] if len(scores) > 1 else None
        valid_scores = [s for s in scores if s is not None]
        max_score = max(valid_scores) if valid_scores else None
        valid_scores = [s for s in scores if s is not None]
        max_score = max(valid_scores) if valid_scores else None

        result = {
            "module_dir": str(module_dir.stem),
            "module": module_name,
            "step0": step0,
            "step1": step1,
            "max_score": max_score,
        }

    # Append result to jsonl file
    with open(OUTPUT_JSONL, "a", encoding="utf-8") as fout:
        fout.write(json.dumps(result, ensure_ascii=False) + "\n")

def load_processed_modules(jsonl_path):
    """Load existing modules from OUTPUT_JSONL."""
    processed = set()
    if not os.path.exists(jsonl_path):
        print(f"[Info] No existing JSONL file found at {jsonl_path}. Starting fresh.")
        return processed

    with open(jsonl_path, "r", encoding="utf-8") as fin:
        for line in fin:
            line = line.strip()
            if not line:
                continue
            try:
                data = json.loads(line)
                if "module_dir" in data:
                    processed.add(data["module_dir"] + "/" + data["module"])
            except:
                pass  # ignore malformed lines

    return processed


if __name__ == "__main__":
    base_dir = Path(os.path.join(project_path, "dataset"))

    selected_modules = load_processed_modules(REFERENCE_JSONL)
    processed_modules = load_processed_modules(OUTPUT_JSONL)
    print(processed_modules)
    for module_dir in sorted(p for p in base_dir.iterdir() if p.is_dir()):
            
        sch_path = module_dir / "module" / "module.kicad_sch"
        print(f"\n---- [Processing {sch_path}] ----")
        if (str(module_dir.stem) + "/" + sch_path.stem) not in selected_modules:
            print(f"[SKIP not already processed] {sch_path.stem}")
            continue
        if (str(module_dir.stem) + "/" + sch_path.stem) in processed_modules:
            print(f"[SKIP already processed] {sch_path.stem}")
            continue
        # if not re.fullmatch(r"block_(\d+)\.kicad_sch", sch_path.name):
        #     print(f"[SKIP non-strict filename] {sch_path.name}")
        #     continue
        agent = LayoutAgent(model='', model_provider="OpenRouter", design_path=str(module_dir / "module"), module_name=sch_path.stem)
        agent.itrative_pcb_layout(max_iters=3)

        scores = getattr(agent, "scores", [])

        # write to JSONL
        record_scores(module_dir.stem, sch_path.stem, scores)

    print(f"\nAll scores saved to: {OUTPUT_JSONL}")